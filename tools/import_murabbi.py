"""Add one month of the Unit Murabbi report to frontend/src/data/murabbi-reports.js.

Usage:
    python tools/import_murabbi.py "responses.csv" --month 2026-10

The CSV is the Google Sheet export (File > Download > CSV) of the monthly
"Reporting Usaha Murabbi" form. Columns are expected in the form's order:
timestamp, email, name, cawangan, then the report questions.

Each person (by email) keeps only their latest submission. Emails are used
for that check and are not written to the site.
"""
import argparse
import csv
import json
import os
import sys
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "frontend", "src", "data", "murabbi-reports.js")
PREFIX = "window.MURABBI_REPORTS = "
COLUMNS = 24  # including the email column
MONTHS = ["Januari", "Februari", "Mac", "April", "Mei", "Jun", "Julai",
          "Ogos", "September", "Oktober", "November", "Disember"]


def parse_time(s):
    for fmt in ("%d/%m/%Y %H:%M:%S", "%d/%m/%Y %H:%M", "%m/%d/%Y %H:%M:%S", "%Y-%m-%d %H:%M:%S"):
        try:
            return datetime.strptime(s.strip(), fmt)
        except ValueError:
            pass
    return datetime.min


def load():
    if not os.path.exists(DATA):
        return {}
    text = open(DATA, encoding="utf-8").read().strip()
    start = text.index(PREFIX) + len(PREFIX)
    return json.loads(text[start:].rstrip(";"))


def save(reports):
    body = json.dumps(dict(sorted(reports.items())), ensure_ascii=False, indent=2)
    with open(DATA, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Unit Murabbi monthly reports. Generated by tools/import_murabbi.py - do not edit by hand.\n")
        f.write(PREFIX + body + ";\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("csv")
    ap.add_argument("--month", required=True, help="report month as YYYY-MM, e.g. 2026-10")
    ap.add_argument("--source", default="", help="where the data came from (shown on the page)")
    ap.add_argument("--note", default="", help="extra note shown under the month")
    args = ap.parse_args()

    year, month = (int(x) for x in args.month.split("-"))
    with open(args.csv, encoding="utf-8-sig", newline="") as f:
        table = [r for r in csv.reader(f) if any(c.strip() for c in r)]
    if not table:
        sys.exit("CSV is empty.")
    header, rows = table[0], table[1:]
    if len(header) < COLUMNS:
        sys.exit(f"Expected {COLUMNS} columns, found {len(header)}. Is this the Murabbi report form?")

    latest = {}
    for r in rows:
        r = (r + [""] * COLUMNS)[:COLUMNS]
        key = r[1].strip().lower() or r[2].strip().lower()
        if key not in latest or parse_time(r[0]) >= parse_time(latest[key][0]):
            latest[key] = r
    kept = sorted(latest.values(), key=lambda r: parse_time(r[0]))

    reports = load()
    reports[args.month] = {
        "label": f"{MONTHS[month - 1]} {year}",
        "source": args.source or os.path.basename(args.csv),
        "note": args.note,
        "received": len(rows),
        "duplicatesRemoved": len(rows) - len(kept),
        "questions": [h.strip() for i, h in enumerate(header[:COLUMNS]) if i != 1],
        "rows": [[c.strip() for i, c in enumerate(r) if i != 1] for r in kept],
    }
    save(reports)
    print(f"{args.month}: {len(rows)} responses, {len(kept)} kept "
          f"({len(rows) - len(kept)} older duplicate(s) dropped) -> {os.path.relpath(DATA, ROOT)}")


if __name__ == "__main__":
    main()
